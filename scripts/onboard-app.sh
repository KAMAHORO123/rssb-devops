#!/usr/bin/env bash
# Onboard an existing NestJS or Next.js application onto the RSSB platform with
# one command (plan v3.2 D12, objective 9).
#
#   scripts/onboard-app.sh --name orders-api --type nestjs \
#       --app-dir ~/code/orders-api --gitops-dir ~/code/platform-gitops [--port 3000] [--database]
#
# App repo:    Dockerfile, .dockerignore, .hadolint.yaml, .trivyignore,
#              .github/workflows/{pr-checks,delivery}.yaml (callers of this repo,
#              pinned to a release), .github/dependabot.yml
# GitOps repo: apps/<name>/base + envs/{uat,staging,prod} (Kustomize). The
#              ApplicationSet deploys every apps/*/envs/* folder automatically.
#
# Existing files are never overwritten. Review the result, then commit both repos.
set -euo pipefail

HERE="$(cd "$(dirname "$0")/.." && pwd)"
T="$HERE/templates"

NAME="" TYPE="" APP_DIR="" GITOPS_DIR="" PORT="" DATABASE=false
OWNER="${RSSB_GITHUB_OWNER:-KAMAHORO123}"
DOMAIN="${RSSB_DOMAIN:-127.0.0.1.nip.io}"

usage() { sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'; exit 1; }
while [ $# -gt 0 ]; do
  case "$1" in
    --name) NAME="$2"; shift 2 ;;
    --type) TYPE="$2"; shift 2 ;;
    --app-dir) APP_DIR="$2"; shift 2 ;;
    --gitops-dir) GITOPS_DIR="$2"; shift 2 ;;
    --port) PORT="$2"; shift 2 ;;
    --database) DATABASE=true; shift ;;
    -h|--help) usage ;;
    *) echo "unknown option: $1" >&2; usage ;;
  esac
done

[ -n "$NAME" ] && [ -n "$TYPE" ] && [ -n "$APP_DIR" ] && [ -n "$GITOPS_DIR" ] || usage
[[ "$NAME" =~ ^[a-z0-9]([a-z0-9-]{0,40}[a-z0-9])?$ ]] || { echo "--name must be a DNS label (lowercase, digits, -)" >&2; exit 1; }
case "$TYPE" in
  nestjs) PORT="${PORT:-3000}"; PROBE=/health ;;
  nextjs) PORT="${PORT:-3000}"; PROBE=/ ;;
  *) echo "--type must be nestjs or nextjs" >&2; exit 1 ;;
esac
[ -f "$APP_DIR/package.json" ] || { echo "$APP_DIR has no package.json" >&2; exit 1; }
[ -f "$APP_DIR/package-lock.json" ] || { echo "$APP_DIR has no package-lock.json (needed for npm ci)" >&2; exit 1; }
[ -f "$GITOPS_DIR/bootstrap/argo-config/applicationset.yaml" ] || { echo "$GITOPS_DIR is not the GitOps repo" >&2; exit 1; }
[ ! -e "$GITOPS_DIR/apps/$NAME" ] || { echo "apps/$NAME already exists in the GitOps repo" >&2; exit 1; }
if [ "$TYPE" = nextjs ] && ! grep -q "standalone" "$APP_DIR"/next.config.* 2>/dev/null; then
  echo "warning: add  output: \"standalone\"  to next.config.js before building (plan A1)" >&2
fi

GITOPS_REPO="$(git -C "$GITOPS_DIR" remote get-url origin | sed -E 's#(git@github.com:|https://github.com/)##; s#\.git$##')"
IMAGE="ghcr.io/$(echo "$OWNER" | tr '[:upper:]' '[:lower:]')/$NAME"

put() {
  local src="$1" dst="$2"
  if [ -e "$dst" ]; then echo "  keep     ${dst#"$APP_DIR"/}"; return; fi
  mkdir -p "$(dirname "$dst")"
  sed -e "s|__NAME__|$NAME|g" -e "s|__PORT__|$PORT|g" -e "s|__GITOPS_REPO__|$GITOPS_REPO|g" "$src" > "$dst"
  echo "  created  ${dst#"$APP_DIR"/}"
}

echo "App repo: $APP_DIR"
put "$T/$TYPE/Dockerfile"        "$APP_DIR/Dockerfile"
put "$T/common/dockerignore"     "$APP_DIR/.dockerignore"
put "$T/common/hadolint.yaml"    "$APP_DIR/.hadolint.yaml"
put "$T/common/trivyignore"      "$APP_DIR/.trivyignore"
put "$T/common/pr-checks.yaml"   "$APP_DIR/.github/workflows/pr-checks.yaml"
put "$T/common/delivery.yaml"    "$APP_DIR/.github/workflows/delivery.yaml"
put "$T/common/dependabot.yml"   "$APP_DIR/.github/dependabot.yml"

echo "GitOps repo: $GITOPS_DIR/apps/$NAME"
python3 - "$GITOPS_DIR/apps/$NAME" "$NAME" "$TYPE" "$PORT" "$PROBE" "$IMAGE" "$DOMAIN" "$DATABASE" <<'PY'
import os, sys
root, name, typ, port, probe, image, domain, database = sys.argv[1:]
database = database == "true"
writable = ["/tmp", "/app/.next/cache"] if typ == "nextjs" else ["/tmp"]
def w(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(text)
    print("  created ", os.path.relpath(path, os.path.dirname(root)))

mounts = "\n".join(f"            - {{ name: writable-{i}, mountPath: {d} }}" for i, d in enumerate(writable))
vols = "\n".join(f"        - {{ name: writable-{i}, emptyDir: {{}} }}" for i, _ in enumerate(writable))
dblabel = '\n        rssb.rw/database-access: "true"   # NetworkPolicy: may reach PostgreSQL' if database else ""
secret = f"""          envFrom:
            - secretRef:
                name: {name}-secrets   # sealed, per environment (envs/*/{name}-secrets.sealed.yaml)
""" if database else ""

w(f"{root}/base/kustomization.yaml", f"""# {name} ({typ}): what every environment shares. Generated by rssb-devops/scripts/onboard-app.sh.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - deployment.yaml
  - service.yaml
  - ingress.yaml
  - vpa.yaml
""")
w(f"{root}/base/deployment.yaml", f"""apiVersion: apps/v1
kind: Deployment
metadata:
  name: {name}
  labels:
    app.kubernetes.io/name: {name}
spec:
  replicas: 1
  revisionHistoryLimit: 5
  selector:
    matchLabels:
      app.kubernetes.io/name: {name}
  strategy:
    rollingUpdate: {{ maxUnavailable: 0, maxSurge: 1 }}
  template:
    metadata:
      labels:
        app.kubernetes.io/name: {name}{dblabel}
    spec:
      securityContext:
        runAsNonRoot: true
        runAsUser: 1000
        runAsGroup: 1000
        seccompProfile: {{ type: RuntimeDefault }}
      topologySpreadConstraints:
        - maxSkew: 1
          topologyKey: kubernetes.io/hostname
          whenUnsatisfiable: ScheduleAnyway
          labelSelector:
            matchLabels:
              app.kubernetes.io/name: {name}
      containers:
        - name: app
          image: {image}   # digest set per environment by CI
          ports:
            - name: http
              containerPort: {port}
{secret}          resources:
            requests: {{ cpu: 50m, memory: 128Mi }}
            limits: {{ memory: 256Mi }}
          livenessProbe:
            httpGet: {{ path: {probe}, port: http }}
            periodSeconds: 10
          readinessProbe:
            httpGet: {{ path: {probe}, port: http }}
            periodSeconds: 5
          lifecycle:
            preStop:
              sleep: {{ seconds: 5 }}
          securityContext:
            allowPrivilegeEscalation: false
            readOnlyRootFilesystem: true
            capabilities: {{ drop: ["ALL"] }}
          volumeMounts:
{mounts}
      volumes:
{vols}
""")
w(f"{root}/base/service.yaml", f"""apiVersion: v1
kind: Service
metadata:
  name: {name}
spec:
  selector:
    app.kubernetes.io/name: {name}
  ports:
    - name: http
      port: {port}
      targetPort: http
""")
w(f"{root}/base/ingress.yaml", f"""apiVersion: networking.k8s.io/v1
kind: Ingress
metadata:
  name: {name}
spec:
  ingressClassName: nginx
  rules:
    - host: HOST_SET_PER_ENVIRONMENT
      http:
        paths:
          - path: /
            pathType: Prefix
            backend:
              service:
                name: {name}
                port: {{ name: http }}
""")
w(f"{root}/base/vpa.yaml", f"""apiVersion: autoscaling.k8s.io/v1
kind: VerticalPodAutoscaler
metadata:
  name: {name}
spec:
  targetRef:
    apiVersion: apps/v1
    kind: Deployment
    name: {name}
  updatePolicy:
    updateMode: "Off"
""")
for env in ("uat", "staging", "prod"):
    ns = "production" if env == "prod" else env
    extra = "  - hpa.yaml\n  - pdb.yaml\n" if env == "prod" else ""
    prodpatch = f"""  - target: {{ kind: Deployment, name: {name} }}
    patch: |-
      - op: remove
        path: /spec/replicas
""" if env == "prod" else ""
    w(f"{root}/envs/{env}/kustomization.yaml", f"""# {name} in {ns}.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
namespace: {ns}
resources:
  - ../../base
{extra}
# CI writes the digest here after the first build on develop (then staging, prod).
images:
  - name: {image}
    newTag: not-built-yet

patches:
  - target: {{ kind: Ingress, name: {name} }}
    patch: |-
      - op: replace
        path: /spec/rules/0/host
        value: {name}-{env}.{domain}
{prodpatch}""")
    if env == "prod":
        w(f"{root}/envs/prod/hpa.yaml", f"""apiVersion: autoscaling/v2
kind: HorizontalPodAutoscaler
metadata:
  name: {name}
spec:
  scaleTargetRef: {{ apiVersion: apps/v1, kind: Deployment, name: {name} }}
  minReplicas: 2
  maxReplicas: 4
  metrics:
    - type: Resource
      resource:
        name: cpu
        target: {{ type: Utilization, averageUtilization: 70 }}
""")
        w(f"{root}/envs/prod/pdb.yaml", f"""apiVersion: policy/v1
kind: PodDisruptionBudget
metadata:
  name: {name}
spec:
  minAvailable: 1
  selector:
    matchLabels:
      app.kubernetes.io/name: {name}
""")
PY

cat <<EOF

Next steps
  1. App repo: commit on a feature branch, open a PR into develop.
  2. GitHub (app repo): secret CONFIG_REPO_DEPLOY_KEY (deploy key with write access
     to $GITOPS_REPO only), branches develop/staging/main protected with the
     required check "checks / all-checks-passed", and a "production" Environment
     with required reviewers.
  3. GitOps repo: PR apps/$NAME. Argo CD creates $NAME-uat, -staging and -prod;
     they wait (not-built-yet) until the first merge to develop writes a digest.
EOF
if [ "$DATABASE" = true ]; then cat <<EOF
  4. Database: create one DB + user per environment, then seal $NAME-secrets
     (DATABASE_URL) into envs/<env>/$NAME-secrets.sealed.yaml with the
     sync-wave "-2" annotation and add it to that kustomization.
EOF
fi
